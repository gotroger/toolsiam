/**
 * งวดที่ "เลื่อน" จากวันปกติ (§17.1)
 *
 * ปกติสลากกินแบ่งรัฐบาลออกรางวัลวันที่ 1 และ 16 ของทุกเดือน แต่บางงวดสำนักงานสลากฯ
 * ประกาศเลื่อน (เช่น ชนวันหยุดยาว) — ใส่ไว้ที่นี่ที่เดียว ปฏิทินทั้งเว็บจะขยับตาม
 *
 * ห้ามเดา: ใส่เฉพาะงวดที่มีประกาศจริง และกรอก `source` ให้ตรวจย้อนได้เสมอ
 */
export interface DrawDateChange {
  /** วันที่ตามกำหนดปกติ (1 หรือ 16) */
  scheduled: string;
  /** วันที่ออกรางวัลจริงตามประกาศ */
  actual: string;
  note: string;
  source: string;
}

export const DRAW_DATE_CHANGES: DrawDateChange[] = [];
