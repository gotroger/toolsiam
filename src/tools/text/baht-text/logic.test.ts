import { describe, it, expect } from 'vitest';
import { bahtText, readInteger } from './logic';

describe('readInteger', () => {
  it.each([
    ['0', 'ศูนย์'],
    ['1', 'หนึ่ง'],
    ['10', 'สิบ'],
    ['11', 'สิบเอ็ด'],
    ['20', 'ยี่สิบ'],
    ['21', 'ยี่สิบเอ็ด'],
    ['100', 'หนึ่งร้อย'],
    ['101', 'หนึ่งร้อยเอ็ด'],
    ['111', 'หนึ่งร้อยสิบเอ็ด'],
    ['1000', 'หนึ่งพัน'],
    ['12345', 'หนึ่งหมื่นสองพันสามร้อยสี่สิบห้า'],
    ['100000', 'หนึ่งแสน'],
    ['1000000', 'หนึ่งล้าน'],
    ['1000001', 'หนึ่งล้านเอ็ด'],
    ['1000011', 'หนึ่งล้านสิบเอ็ด'],
    ['2000001', 'สองล้านเอ็ด'],
    ['21000000', 'ยี่สิบเอ็ดล้าน'],
    ['1000000000000', 'หนึ่งล้านล้าน'],
    ['1000000000001', 'หนึ่งล้านล้านเอ็ด'],
    ['007', 'เจ็ด'],
  ])('%s → %s', (input, expected) => {
    expect(readInteger(input)).toBe(expected);
  });
});

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1.5, 'หนึ่งบาทห้าสิบสตางค์'],
    [0.25, 'ยี่สิบห้าสตางค์'],
    [0.01, 'หนึ่งสตางค์'],
    [1234567.89, 'หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์'],
    [-5, 'ลบห้าบาทถ้วน'],
  ])('%s → %s', (input, expected) => {
    expect(bahtText(input)).toBe(expected);
  });

  it('รับ string ที่มีคอมมา/ช่องว่าง และปัดสตางค์', () => {
    expect(bahtText('1,234.50')).toBe('หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์');
    expect(bahtText(' 99 ')).toBe('เก้าสิบเก้าบาทถ้วน');
    expect(bahtText('1.005')).toBe('หนึ่งบาทหนึ่งสตางค์');
    expect(bahtText('0.999')).toBe('หนึ่งบาทถ้วน'); // ทดสตางค์ขึ้นบาท
    // half-up rounding fix
    expect(bahtText('0.145')).toBe('สิบห้าสตางค์');
    expect(bahtText('0.285')).toBe('ยี่สิบเก้าสตางค์');
    expect(bahtText('2.575')).toBe('สองบาทห้าสิบแปดสตางค์');
    expect(bahtText('0.5')).toBe('ห้าสิบสตางค์');
    expect(bahtText('1.1')).toBe('หนึ่งบาทสิบสตางค์');
  });

  it('รับตัวเลขใหญ่กว่า Number.MAX_SAFE_INTEGER ผ่าน string', () => {
    expect(bahtText('123456789012345678')).toBe(
      'หนึ่งแสนสองหมื่นสามพันสี่ร้อยห้าสิบหกล้านล้านเจ็ดแสนแปดหมื่นเก้าพันสิบสองล้านสามแสนสี่หมื่นห้าพันหกร้อยเจ็ดสิบแปดบาทถ้วน',
    );
  });

  it('โยน error เมื่อรูปแบบผิด', () => {
    expect(() => bahtText('abc')).toThrow('รูปแบบตัวเลขไม่ถูกต้อง');
    expect(() => bahtText('1.2.3')).toThrow('รูปแบบตัวเลขไม่ถูกต้อง');
    expect(() => bahtText('')).toThrow('รูปแบบตัวเลขไม่ถูกต้อง');
  });
});

describe('ตัวเลขชนิด number ใช้เส้นทางเดียวกับข้อความ', () => {
  it('1.005 ได้ผลเท่ากับ "1.005" (ไม่ปัดตาม float 1.00499…)', () => {
    expect(bahtText(1.005)).toBe(bahtText('1.005'));
    expect(bahtText(1.005)).toBe('หนึ่งบาทหนึ่งสตางค์');
  });

  it('ค่าที่ปกติยังได้ผลเดิม', () => {
    expect(bahtText(1234.5)).toBe('หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์');
    expect(bahtText(0)).toBe('ศูนย์บาทถ้วน');
    expect(bahtText(-21)).toBe('ลบยี่สิบเอ็ดบาทถ้วน');
  });

  it('ตัวเลขใหญ่ตั้งแต่ 1e21 (รูปเลขยกกำลัง) ไม่ throw', () => {
    expect(bahtText(1e21)).toBe(bahtText('1000000000000000000000'));
    expect(bahtText(1.5e22)).toBe(bahtText('15000000000000000000000'));
  });

  it('ตัวเลขเล็กมากรูปเลขยกกำลังอ่านเป็นศูนย์บาทถ้วน', () => {
    expect(bahtText(1e-7)).toBe('ศูนย์บาทถ้วน');
    expect(bahtText(5e-3)).toBe('หนึ่งสตางค์');
  });

  it('NaN และ Infinity แจ้งข้อผิดพลาดภาษาไทย', () => {
    expect(() => bahtText(Number.NaN)).toThrow('ตัวเลข');
    expect(() => bahtText(Infinity)).toThrow('ตัวเลข');
  });
});
