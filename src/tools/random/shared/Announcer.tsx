/**
 * ช่องประกาศผลให้ screen reader — ทุกเครื่องมือในหมวดใช้ตัวนี้ตัวเดียว
 *
 * ต้อง **mount ค้างไว้ตลอด** ไม่ใช่โผล่มาพร้อมผล เพราะ screen reader หลายตัวไม่อ่าน live region
 * ที่เพิ่งถูกใส่ลง DOM พร้อมข้อความในจังหวะเดียวกัน และต้องได้รับ **เฉพาะผลสุดท้าย**
 * — ถ้าผูก aria-live ไว้กับกล่องที่รัวค่าหลอก 14 เฟรม ผู้ใช้จะได้ยินค่าหลอกหรือรหัสผ่านสุ่มทิ้งรัว ๆ
 * กล่องที่มองเห็นจึงใส่แค่ aria-busy ระหว่างลุ้น ส่วนเสียงมาจากที่นี่ที่เดียว
 *
 * `runId` เป็น key ของข้อความ: สุ่มซ้ำแล้วได้ผลเหมือนเดิม ข้อความเดิมก็ถูกใส่ใหม่และถูกอ่านอีกครั้ง
 */
export function ResultAnnouncer({ message, runId }: { message: string; runId: number }) {
  return (
    <p role="status" className="sr-only">
      <span key={runId}>{message}</span>
    </p>
  );
}
