import { describe, it, expect } from 'vitest';
import { toCsv } from './clipboard';

describe('toCsv', () => {
  it('ต่อหัวตารางกับแถวด้วยคอมมาและขึ้นบรรทัดใหม่', () => {
    expect(toCsv(['วันที่', 'ชื่อ'], [['2026-01-01', 'วันขึ้นปีใหม่']]))
      .toBe('วันที่,ชื่อ\n2026-01-01,วันขึ้นปีใหม่');
  });

  it('ครอบด้วยอัญประกาศเมื่อมีคอมมา อัญประกาศ หรือขึ้นบรรทัดใหม่', () => {
    expect(toCsv(['a'], [['x,y']])).toBe('a\n"x,y"');
    expect(toCsv(['a'], [['เขาว่า "ดี"']])).toBe('a\n"เขาว่า ""ดี"""');
    expect(toCsv(['a'], [['บรรทัด1\nบรรทัด2']])).toBe('a\n"บรรทัด1\nบรรทัด2"');
  });

  it('ตัวเลขไม่ถูกครอบด้วยอัญประกาศ', () => {
    expect(toCsv(['n'], [[1234.5]])).toBe('n\n1234.5');
  });
});
